"""Streamlit dashboard: historical 2024 test-season predictions vs the closing spread.

Run:  streamlit run streamlit_app.py
Reads the committed snapshot generated by verify.py; no database or training at startup.
Research visualization only. Not betting advice; no live odds are fetched.
"""
import json
from pathlib import Path

import altair as alt
import pandas as pd
import streamlit as st

st.set_page_config(page_title="Sports Forecasting Lab | NFL Research", page_icon="🏈", layout="wide")
SNAPSHOT_PATH = Path(__file__).resolve().parent / "reports" / "metrics.json"
REPO_URL = "https://github.com/santhoshchakilamcs/sports-forecasting-lab"


@st.cache_data(show_spinner=False)
def load(snapshot_text: str) -> dict:
    """Cache by file contents so regenerated verification results invalidate the cache."""
    payload = json.loads(snapshot_text)
    if payload["schema_version"] != 1:
        raise ValueError("Unsupported dashboard snapshot. Run python verify.py again.")
    for name in ("metadata", "pred_test", "metrics", "drift", "simulation"):
        payload[name] = pd.DataFrame(payload[name])
    payload["calibration"] = {name: pd.DataFrame(rows)
                              for name, rows in payload["calibration"].items()}
    return payload


try:
    r = load(SNAPSHOT_PATH.read_text(encoding="utf-8"))
except (OSError, ValueError, KeyError, TypeError):
    st.error("Verified dashboard data is missing or invalid. Run `python verify.py` locally "
             "and commit reports/metrics.json before deploying. No replacement data is generated.")
    st.stop()

pred = r["pred_test"]

st.title("🏈 Sports Forecasting Lab")
st.subheader(f"NFL {r['test_season']} · Out-of-sample research")
st.caption("Personal research project on public nflverse data. Models trained on 2021-2023, "
           "evaluated on 2024. Not affiliated with Susquehanna or any employer. "
           "No betting, trading, or real money.")
st.info("Historical results, not a live game feed. Every prediction and chart comes from "
        "the committed output of verify.py; opening this site does not retrain the models.")

with st.sidebar:
    st.header("Research notebook")
    st.markdown(f"[Source code & methodology]({REPO_URL})")
    st.markdown(f"[Full verification report]({REPO_URL}/blob/main/reports/verify_output.txt)")
    st.caption("Real public data · Prior-games-only features · Held-out test season")
    st.download_button("Download test predictions", pred.to_csv(index=False),
                       file_name="nfl_test_predictions.csv", mime="text/csv")

cards = st.columns(4)
cards[0].metric("Public play-by-play rows", f"{r['data_counts']['pbp_plays']:,}")
cards[1].metric("Training games", f"{r['n_train']:,}")
cards[2].metric("Held-out games", f"{r['n_test']:,}")
cards[3].metric("Season simulations", f"{r['sim_metrics']['sim_n']:,}")

week = st.selectbox(f"{r['test_season']} week", sorted(pred["week"].unique()))
wk = pred[pred["week"] == week].copy()
wk["matchup"] = wk["away_team"] + " @ " + wk["home_team"]
wk["model_side_vs_line"] = (wk["margin_spread_ridge"] > wk["spread_line"]).map(
    {True: "home", False: "away"})
wk.loc[wk["margin_spread_ridge"] == wk["spread_line"], "model_side_vs_line"] = "no pick"
wk["home_covered"] = (wk["result"] > wk["spread_line"]).map({True: "home", False: "away"})
wk.loc[wk["result"] == wk["spread_line"], "home_covered"] = "push"
table = wk[["matchup", "game_type", "p_logreg", "p_xgboost", "p_spread_ridge", "p_market_spread",
            "margin_spread_ridge", "spread_line", "model_side_vs_line", "result", "home_covered"]]
table = table.rename(columns={
    "p_logreg": "P(home) logreg", "p_xgboost": "P(home) xgboost",
    "p_spread_ridge": "P(home) spread model", "p_market_spread": "P(home) from closing line",
    "margin_spread_ridge": "predicted home margin", "spread_line": "closing line (home fav +)",
    "model_side_vs_line": "model side vs line", "result": "actual home margin",
    "home_covered": "covering side"})
st.subheader(f"Week {week}")
st.caption("All probabilities refer to the home team. A positive margin/line means home "
           "favored. Model side vs line is a historical comparison, not a recommendation.")
st.dataframe(table.style.format(precision=3), width="stretch", hide_index=True)

c1, c2 = st.columns(2)
with c1:
    st.subheader("Test-season metrics (2024)")
    st.dataframe(r["metrics"][["model", "accuracy", "log_loss", "brier", "ece", "ats_hit_rate"]]
                 .style.format(precision=4), hide_index=True)
with c2:
    st.subheader("Calibration (10 bins)")
    cal = pd.concat([df.assign(model=name) for name, df in r["calibration"].items()])
    cal = cal[cal["n"] > 0]
    diag = alt.Chart(pd.DataFrame({"x": [0, 1], "y": [0, 1]})).mark_line(
        strokeDash=[4, 4], color="gray").encode(x="x", y="y")
    pts = alt.Chart(cal).mark_line(point=True).encode(
        x=alt.X("mean_pred", title="mean predicted P(home win)", scale=alt.Scale(domain=[0, 1])),
        y=alt.Y("actual_rate", title="actual home win rate", scale=alt.Scale(domain=[0, 1])),
        color="model", tooltip=["model", "bin", "n", "mean_pred", "actual_rate"])
    st.altair_chart(diag + pts, width="stretch")

st.caption("The closing-spread benchmark has lower test log loss than all three models. "
           "The against-the-spread results do not establish a statistically significant edge.")

st.subheader(f"Monte Carlo season simulation ({r['sim_metrics']['sim_n']:,} sims, "
             f"seed {r['sim_metrics']['sim_seed']})")
st.caption(f"2024 regular season simulated from week {r['sim_metrics']['sim_cutoff_week']} "
           "cutoff with features frozen at the cutoff; compared to actual final wins. "
           "Division ties use random tiebreakers, not official NFL rules.")
st.dataframe(r["simulation"].style.format(precision=2), hide_index=True, width="stretch")

with st.expander("Feature drift and data provenance"):
    st.caption("Train-versus-test standardized mean differences; flags are informational, "
               "not pass/fail results.")
    st.dataframe(r["drift"], hide_index=True, width="stretch")
    st.dataframe(r["metadata"], hide_index=True, width="stretch")
